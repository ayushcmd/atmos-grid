#!/usr/bin/env python
"""
Surface AQI Estimation Pipeline Runner.

Coordinates the end-to-end Pipeline A:
1. Loads processed CPCB monitoring station observations (data/processed/cpcb_daily_aqi.csv).
2. Generates temporal, spatial, and autoregressive features.
3. Performs a chronological, non-leaking train/test split.
4. Trains an XGBoost regressor and compares it with a historical baseline.
5. Evaluates held-out performance (MAE, RMSE, R²).
6. Serializes model weights, prediction tables, and metric summaries.

Usage:
    .venv\\Scripts\\python backend\\scripts\\run_aqi_pipeline.py
"""

from __future__ import annotations

import logging
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd
from backend.src.models.aqi_model import (
    chronological_split,
    engineer_features,
    save_pipeline_artifacts,
    train_aqi_xgboost,
)

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger("run_aqi_pipeline")


def main():
    data_path = PROJECT_ROOT / "data" / "processed" / "cpcb_daily_aqi.csv"

    if not data_path.exists():
        logger.error(
            "Processed ground data not found at %s. Please run run_cpcb_acquisition.py first.",
            data_path,
        )
        sys.exit(1)

    print("\n" + "=" * 70)
    print("       ATMOSGRID: SURFACE AQI ESTIMATION PIPELINE (PIPELINE A)")
    print("=" * 70)

    # 1. Load data
    logger.info("Loading CPCB daily AQI observations from %s", data_path)
    df = pd.read_csv(data_path)
    logger.info("Loaded %d daily station observations", len(df))

    # 2. Engineer features
    target_col = "aqi"
    df_feat, feature_cols = engineer_features(df, target_col=target_col, include_lags=True)
    logger.info("Engineered %d features: %s", len(feature_cols), feature_cols)

    # Drop any remaining NaN rows generated by lags
    df_clean = df_feat.dropna(subset=feature_cols + [target_col]).reset_index(drop=True)
    logger.info("Usable dataset after feature engineering: %d samples", len(df_clean))

    # 3. Chronological split (80% train, 20% held-out test)
    train_df, test_df = chronological_split(df_clean, test_ratio=0.20)
    print(f"\nTrain Observation Period : {train_df['date'].min().date()} to {train_df['date'].max().date()} ({len(train_df)} samples)")
    print(f"Test Observation Period  : {test_df['date'].min().date()} to {test_df['date'].max().date()} ({len(test_df)} samples)")

    X_train = train_df[feature_cols]
    y_train = train_df[target_col]
    X_test = test_df[feature_cols]
    y_test = test_df[target_col]

    # 4. Train XGBoost
    logger.info("Training XGBoost regression model...")
    model, metrics = train_aqi_xgboost(
        X_train=X_train,
        y_train=y_train,
        X_test=X_test,
        y_test=y_test,
        n_estimators=120,
        max_depth=4,
        learning_rate=0.05,
    )

    # 5. Save artifacts
    y_pred_test = model.predict(X_test)
    artifacts = save_pipeline_artifacts(
        model=model,
        metrics=metrics,
        test_df=test_df,
        y_pred_test=y_pred_test,
        target_col=target_col,
        output_dir=PROJECT_ROOT,
    )

    # 6. Display report
    print("\n" + "=" * 70)
    print("                    EVALUATION SUMMARY")
    print("=" * 70)
    test_m = metrics["test_metrics"]
    train_m = metrics["train_metrics"]
    base_m = metrics["baseline_comparison"]["baseline_test_metrics"]

    print(f"Train Metrics        : MAE = {train_m['mae']}, RMSE = {train_m['rmse']}, R² = {train_m['r2']}")
    print(f"Held-out Test Metrics: MAE = {test_m['mae']}, RMSE = {test_m['rmse']}, R² = {test_m['r2']}")
    print(f"Historical Baseline  : MAE = {base_m['mae']}, RMSE = {base_m['rmse']}, R² = {base_m['r2']}")
    print(f"MAE Error Reduction  : {metrics['baseline_comparison']['mae_reduction_percent']}% over baseline")
    print("-" * 70)
    print("Top Predictive Features:")
    for feat, imp in list(metrics["feature_importance"].items())[:5]:
        print(f"  - {feat:18s}: {imp:.4f}")
    print("-" * 70)
    print("Saved Artifacts:")
    for k, path in artifacts.items():
        print(f"  - {k:20s}: {path}")
    print("=" * 70 + "\n")


if __name__ == "__main__":
    main()
